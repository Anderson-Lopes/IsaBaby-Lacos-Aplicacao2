/*
# IsaBaby Laços — auth, catalog and orders schema

1. New Tables
- `profiles` — application profile for each signed-up user.
  - `id` (uuid, primary key, references auth.users, defaults to the authenticated user)
  - `username` (text, unique, required) — display/login name shown in the app.
  - `role` (text, not null, default 'customer') — 'admin' or 'customer'. NOT client-writable.
  - `must_change_password` (boolean, not null, default false) — flags the pre-defined admin account so the app can prompt a password change on first sign-in.
  - `created_at` (timestamptz, default now()).
- `products` — catalog of handmade bows.
  - `id` (uuid, primary key)
  - `name`, `model`, `description` (text)
  - `price` (numeric, not null, > 0 enforced by trigger)
  - `quantity` (integer, not null, >= 0 enforced by trigger)
  - `status` (text, not null, default 'ativo') — 'ativo' | 'sob_encomenda' | 'indisponivel'
  - `image_url` (text, nullable)
  - `created_at` (timestamptz, default now())
- `orders` — purchase orders placed by customers.
  - `id` (uuid, primary key)
  - `number` (integer, generated always as identity) — human-friendly order number.
  - `user_id` (uuid, references auth.users, defaults to the authenticated user) — owner.
  - `status` (text, not null, default 'pendente')
  - `pickup_date` (date, nullable), `pickup_time` (text, nullable)
  - `total` (numeric, not null)
  - `created_at` (timestamptz, default now())
- `order_items` — personalized items inside an order.
  - `id` (uuid, primary key)
  - `order_id` (uuid, references orders, on delete cascade)
  - `product_id` (uuid, references products, on delete set null)
  - `product_name`, `color`, `size` (text, not null)
  - `quantity` (integer, not null, check >= 1)
  - `unit_price` (numeric, not null), `notes` (text, nullable)

2. Security
- RLS enabled on all four tables.
- `profiles`: authenticated users can SELECT their own row; users can INSERT their own profile on first sign-in (role forced to 'customer' by a trigger); users can UPDATE their own username only (role/must_change_password revoked at column level).
- `products`: SELECT open to anon + authenticated (catalog is public); INSERT/UPDATE/DELETE restricted to admins, enforced server-side via a `is_admin()` security definer helper.
- `orders` / `order_items`: customers manage only their own orders; admins can read all orders (to manage production later).
- Password changes go through Supabase Auth (updateUser), never through tables.

3. Notes
- The admin bootstrap account is NOT created in this migration — it is created via the auth admin API after this migration.
- Order numbers are generated by the database identity column, so concurrent orders never collide.
*/

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  username text NOT NULL,
  role text NOT NULL DEFAULT 'customer' CHECK (role IN ('admin', 'customer')),
  must_change_password boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.products (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL,
  model text NOT NULL,
  description text NOT NULL DEFAULT '',
  price numeric(10,2) NOT NULL CHECK (price > 0),
  quantity integer NOT NULL CHECK (quantity >= 0),
  status text NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'sob_encomenda', 'indisponivel')),
  image_url text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.orders (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number integer GENERATED ALWAYS AS IDENTITY,
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'pendente' CHECK (status IN ('pendente','confirmado','em_producao','pronto_retirada','entregue','cancelado')),
  pickup_date date,
  pickup_time text,
  total numeric(10,2) NOT NULL CHECK (total >= 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.order_items (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  order_id uuid NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
  product_id uuid REFERENCES public.products(id) ON DELETE SET NULL,
  product_name text NOT NULL,
  color text NOT NULL,
  size text NOT NULL,
  quantity integer NOT NULL CHECK (quantity >= 1),
  unit_price numeric(10,2) NOT NULL,
  notes text
);

CREATE INDEX IF NOT EXISTS orders_user_idx ON public.orders (user_id);
CREATE INDEX IF NOT EXISTS order_items_order_idx ON public.order_items (order_id);

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.order_items ENABLE ROW LEVEL SECURITY;

-- is_admin helper (security definer so RLS policies can call it without recursion)
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS boolean
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
STABLE
AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles
    WHERE id = auth.uid() AND role = 'admin'
  );
$$;

-- profiles: role is forced to 'customer' on self-signup; admin role is only set via service role
CREATE OR REPLACE FUNCTION public.force_customer_role()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF NEW.role <> 'customer' THEN
    NEW.role := 'customer';
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS profiles_force_customer_role ON public.profiles;
CREATE TRIGGER profiles_force_customer_role
BEFORE INSERT ON public.profiles
FOR EACH ROW EXECUTE FUNCTION public.force_customer_role();

GRANT SELECT ON public.profiles TO authenticated;
GRANT INSERT ON public.profiles TO authenticated;
REVOKE UPDATE ON public.profiles FROM authenticated;
GRANT UPDATE (username) ON public.profiles TO authenticated;

DROP POLICY IF EXISTS "select_own_profile" ON public.profiles;
CREATE POLICY "select_own_profile" ON public.profiles FOR SELECT
TO authenticated USING (auth.uid() = id);

DROP POLICY IF EXISTS "insert_own_profile" ON public.profiles;
CREATE POLICY "insert_own_profile" ON public.profiles FOR INSERT
TO authenticated WITH CHECK (auth.uid() = id);

DROP POLICY IF EXISTS "update_own_username" ON public.profiles;
CREATE POLICY "update_own_username" ON public.profiles FOR UPDATE
TO authenticated USING (auth.uid() = id) WITH CHECK (auth.uid() = id);

-- products: public catalog read, admin-only writes
GRANT SELECT ON public.products TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON public.products TO authenticated;

DROP POLICY IF EXISTS "catalog_is_public" ON public.products;
CREATE POLICY "catalog_is_public" ON public.products FOR SELECT
TO anon, authenticated USING (true);

DROP POLICY IF EXISTS "admins_manage_products" ON public.products;
CREATE POLICY "admins_manage_products" ON public.products FOR INSERT
TO authenticated WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "admins_update_products" ON public.products;
CREATE POLICY "admins_update_products" ON public.products FOR UPDATE
TO authenticated USING (public.is_admin()) WITH CHECK (public.is_admin());

DROP POLICY IF EXISTS "admins_delete_products" ON public.products;
CREATE POLICY "admins_delete_products" ON public.products FOR DELETE
TO authenticated USING (public.is_admin());

-- orders: customers own their orders, admins can read all
GRANT SELECT, INSERT, UPDATE ON public.orders TO authenticated;
GRANT INSERT ON public.order_items TO authenticated;
GRANT SELECT ON public.order_items TO authenticated;

DROP POLICY IF EXISTS "select_own_orders" ON public.orders;
CREATE POLICY "select_own_orders" ON public.orders FOR SELECT
TO authenticated USING (auth.uid() = user_id OR public.is_admin());

DROP POLICY IF EXISTS "insert_own_orders" ON public.orders;
CREATE POLICY "insert_own_orders" ON public.orders FOR INSERT
TO authenticated WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "update_own_orders" ON public.orders;
CREATE POLICY "update_own_orders" ON public.orders FOR UPDATE
TO authenticated USING (auth.uid() = user_id) WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "select_own_order_items" ON public.order_items;
CREATE POLICY "select_own_order_items" ON public.order_items FOR SELECT
TO authenticated USING (
  EXISTS (SELECT 1 FROM public.orders WHERE orders.id = order_items.order_id AND (orders.user_id = auth.uid() OR public.is_admin()))
);

DROP POLICY IF EXISTS "insert_own_order_items" ON public.order_items;
CREATE POLICY "insert_own_order_items" ON public.order_items FOR INSERT
TO authenticated WITH CHECK (
  EXISTS (SELECT 1 FROM public.orders WHERE orders.id = order_items.order_id AND orders.user_id = auth.uid())
);

